# Enunciado 2:
# Creá una lista con las temperaturas de la última semana:
# [18, 22, 25, 21, 19, 17, 20].
#
# Mostrá:
# - La primera temperatura
# - La última temperatura
# - Las primeras tres temperaturas
# - La lista al revés
# ============================================================

# Crear la lista de temperaturas
temperaturas = [18, 22, 25, 21, 19, 17, 20]

# Mostrar el primer elemento
print(temperaturas[0])

# Mostrar el último elemento
print(temperaturas[-1])

# Mostrar los primeros tres elementos
print(temperaturas[:3])

# Mostrar la lista al revés
print(temperaturas[::-1])
