def calcular_area_rectangulo(base, altura):
    area = base * altura
    print(f"El rectángulo de {base} x {altura} tiene área {area}")


calcular_area_rectangulo(5, 3)
calcular_area_rectangulo(10, 7)
calcular_area_rectangulo(2.5, 4)
